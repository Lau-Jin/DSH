/**
 * dsh-session-index 一键安装 / 校验 / 卸载 / 自动打包。
 *
 * 目标：命令行压到最少——只运行一次 `node install.mjs`（或双击 install.cmd），之后
 *   - DSH 的 MCP 连接自动配置好
 *   - Skill 自动装好（客户端不支持 prompts/resources 时的兜底）
 *   - server 启动自动建索引；新会话由文件事件自动识别，无需重启 DSH
 *   - 自动生成可分发插件包与技能包（无需手工压缩）
 *
 * 用法：
 *   node install.mjs                 安装（幂等，重复运行安全）
 *   node install.mjs --dry-run      预览将要做的改动，不写任何文件
 *   node install.mjs --verify       校验当前安装状态
 *   node install.mjs --uninstall    卸载（移除标记块与自动安装的 Skill，可回滚）
 *   node install.mjs --reset-env    用默认值覆盖已有的 env 自定义配置
 *   node install.mjs --profile web  指定 profile，默认 desktop
 *   node install.mjs --json         以 JSON 输出结果
 *
 * 安全：只改 cordis.patch.yml 中带标记的整段；写前自动备份；不改动其它任何条目。
 *       重复安装（含从 GitHub 拉取更新后重跑）会保留标记块内已有的 env 自定义值。
 *
 * 路径全部基于脚本自身目录解析，因此从任意位置 clone 仓库后直接运行即可，
 * 不依赖 cwd，也不需要把插件放到某个固定路径。
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

import { packAll } from './lib/pack.mjs';

const PLUGIN_DIR = path.dirname(fileURLToPath(import.meta.url));
const START = '# >>> session-index (auto-generated by install.mjs, safe to delete) >>>';
const END = '# <<< session-index <<<';
const ID = 'mcp-session-index';

function parseArgs(argv) {
  const o = { dryRun: false, verify: false, uninstall: false, json: false, profile: '', resetEnv: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--dry-run') o.dryRun = true;
    else if (a === '--verify') o.verify = true;
    else if (a === '--uninstall') o.uninstall = true;
    else if (a === '--json') o.json = true;
    else if (a === '--reset-env') o.resetEnv = true;
    else if (a === '--profile' && argv[i + 1]) o.profile = argv[++i];
  }
  return o;
}
function stamp() {
  return new Date().toISOString().replace(/[:.]/g, '-');
}
function backup(file) {
  const dest = `${file}.bak-${stamp()}`;
  fs.copyFileSync(file, dest);
  return dest;
}
function hasZstd(nodeBin) {
  const r = spawnSync(nodeBin, ['-e', 'process.stdout.write(typeof require("zlib").zstdDecompressSync)'], {
    encoding: 'utf8',
    timeout: 8000,
  });
  return r.status === 0 && String(r.stdout || '').trim() === 'function';
}
function resolveNode(env) {
  const candidates = [env.SESSION_INDEX_NODE, process.execPath, 'node'].filter(Boolean);
  for (const c of candidates) {
    try {
      if (c !== 'node' && !fs.existsSync(c)) continue;
      if (hasZstd(c)) return { bin: c, ok: true };
    } catch {
      // 继续下一个候选
    }
  }
  return { bin: process.execPath, ok: false };
}
function resolvePaths(opts, env) {
  const dshHome = env.DSH_HOME || path.join(os.homedir(), '.dsh');
  const profile = opts.profile || env.DSH_PROFILE || 'desktop';
  const profileDir = env.DSH_PROFILE_DIR || path.join(dshHome, 'profiles', profile);
  return {
    dshHome,
    profile,
    profileDir,
    profileManifest: path.join(profileDir, 'package.json'),
    patchFile: path.join(profileDir, 'cordis.patch.yml'),
    indexDir: env.SESSION_INDEX_DIR || path.join(dshHome, 'session-index'),
    skillSrc: path.join(PLUGIN_DIR, 'skill', 'SKILL.md'),
    skillDest: path.join(dshHome, 'skills', 'session-index', 'SKILL.md'),
    serverFile: path.join(PLUGIN_DIR, 'server.mjs'),
  };
}
const yq = (s) => `'${String(s).replace(/'/g, "''")}'`;

/** 提取已有标记块内的 env 原始值（保留引号），用于更新安装时不覆盖用户自定义。 */
function parseExistingEnv(text) {
  const s = text.indexOf(START);
  const e = text.indexOf(END);
  if (s === -1 || e === -1 || e <= s) return {};
  const out = {};
  for (const line of text.slice(s, e).split(/\r?\n/)) {
    const m = /^ {6}([A-Z][A-Z0-9_]*):\s*(.+?)\s*$/.exec(line);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

function buildBlock(p, nodeBin, envOverrides = {}) {
  const env = {
    DSH_HOME: yq(p.dshHome),
    SESSION_INDEX_DIR: yq(p.indexDir),
    SESSION_INDEX_AUTO: '"1"',
    SESSION_INDEX_AUTO_INTERVAL_MS: '"60000"',
    SESSION_INDEX_AUTO_QUIET_MS: '"45000"',
    SESSION_INDEX_WATCH: '"1"',
    ...envOverrides,
  };
  const lines = [
    START,
    `- id: ${ID}`,
    "  name: '@deepseek-ai/dsh-mcp-client'",
    '  config:',
    '    serverName: session-index',
    '    transport: stdio',
    `    command: ${yq(nodeBin)}`,
    `    args: [ ${yq(p.serverFile)} ]`,
    '    env:',
  ];
  for (const [k, v] of Object.entries(env)) lines.push(`      ${k}: ${v}`);
  lines.push(END);
  return lines.join('\n');
}
function patchText(original, block, removeOnly = false) {
  const crlf = original.includes('\r\n');
  const text = original.replace(/\r\n/g, '\n');
  const s = text.indexOf(START);
  const e = text.indexOf(END);
  let next;
  if (s !== -1 && e !== -1 && e > s) {
    next = text.slice(0, s) + (removeOnly ? '' : block) + text.slice(e + END.length);
    if (removeOnly) next = next.replace(/\n{3,}/g, '\n\n');
  } else if (removeOnly) {
    next = text;
  } else {
    next = text.replace(/\s*$/, '') + '\n\n' + block + '\n';
  }
  return crlf ? next.replace(/\n/g, '\r\n') : next;
}
function readIndexState(indexDir) {
  const p = path.join(indexDir, 'meta.json');
  if (!fs.existsSync(p)) return { exists: false, sessions: 0 };
  try {
    const m = JSON.parse(fs.readFileSync(p, 'utf8'));
    return { exists: true, sessions: Object.keys(m.sessions || {}).length, builtAt: m.builtAt };
  } catch {
    return { exists: false, sessions: 0, corrupt: true };
  }
}

/**
 * 这个插件是不是已经以「DSH bundle」方式装进 profile 了？
 *
 * 是的话就不能再往 cordis.patch.yml 写 mcp 行：bundle 的 cordis.patch.yml 已经
 * insert 了一条同 id（mcp-session-index）的配置，重复会出现两条同 id 行。
 * 从插件页 / pnpm 安装走的正是这条路径。
 */
function bundleRegistered(profileManifest) {
  try {
    const pkg = JSON.parse(fs.readFileSync(profileManifest, 'utf8'));
    const list = pkg?.dsh?.profile?.bundles;
    return Array.isArray(list) && list.includes('dsh-session-index');
  } catch {
    return false;
  }
}

/**
 * 记录 MCP 入口的绝对路径。
 *
 * bundle 方式下 cordis.patch.yml 里的 args 是用 `!!js` 读这个文件的——因为安装位置
 * 由 pnpm 决定，配置里没法预先写死。宿主半身（lib/index.mjs）每次启动也会刷新它；
 * 这里提前写一遍，安装完立刻可用（不必等 DSH 重启后的第一次 apply）。
 */
function writeServerPathFile(indexDir, serverFile) {
  const target = path.join(indexDir, 'server-path.txt');
  fs.mkdirSync(indexDir, { recursive: true });
  const next = serverFile + '\n';
  let current = null;
  try {
    current = fs.readFileSync(target, 'utf8');
  } catch {
    current = null;
  }
  if (current === next) return { target, changed: false };
  fs.writeFileSync(target, next, 'utf8');
  return { target, changed: true };
}

function verify(p, nodeBin) {
  const checks = [];
  const add = (name, ok, detail) => checks.push({ name, ok, detail });
  add('插件目录', fs.existsSync(p.serverFile), p.serverFile);
  add('Node >= 22.15 且支持 zstd', hasZstd(nodeBin), nodeBin);
  add('profile 配置文件', fs.existsSync(p.patchFile), p.patchFile);
  const byBundle = bundleRegistered(p.profileManifest);
  let raw = '';
  try {
    raw = fs.readFileSync(p.patchFile, 'utf8');
  } catch {
    // ignore
  }
  add(
    'MCP 条目已注册',
    byBundle || (raw.includes(START) && raw.includes(ID)),
    byBundle ? 'bundle 挂载（cordis.patch.yml @ 插件包内）' : ID,
  );
  add('自动注入 Skill', fs.existsSync(p.skillDest), p.skillDest);
  const idx = readIndexState(p.indexDir);
  add('索引已生成', idx.exists && idx.sessions > 0, `${idx.sessions} 个会话 / ${idx.builtAt || '-'}`);
  return { ok: checks.every((c) => c.ok), checks, index: idx, bundle: byBundle };
}

function main() {
  const opts = parseArgs(process.argv.slice(2));
  const env = process.env;
  const p = resolvePaths(opts, env);
  const node = resolveNode(env);
  const byBundle = bundleRegistered(p.profileManifest);
  const out = {
    action: opts.verify ? 'verify' : opts.uninstall ? 'uninstall' : opts.dryRun ? 'dry-run' : 'install',
    pluginDir: PLUGIN_DIR, ...p, nodeBin: node.bin, nodeOk: node.ok, bundle: byBundle, changes: [], backups: [],
  };

  if (!node.ok) {
    out.error = '未找到支持 zlib.zstdDecompressSync 的 Node（需 >= 22.15）。可设置 SESSION_INDEX_NODE 指定路径。';
    if (!opts.json) console.error(out.error);
    else process.stdout.write(JSON.stringify(out, null, 2) + '\n');
    process.exitCode = 1;
    return;
  }
  if (opts.verify) {
    const result = verify(p, node.bin);
    out.verify = result;
    out.ok = result.ok;
    if (opts.json) process.stdout.write(JSON.stringify(out, null, 2) + '\n');
    else {
      for (const c of result.checks) console.log(`${c.ok ? 'OK  ' : 'FAIL'}  ${c.name}${c.detail ? ' — ' + c.detail : ''}`);
      console.log(result.ok ? '\n安装状态正常。' : '\n有未满足项，运行 node install.mjs 完成安装。');
    }
    if (!result.ok) process.exitCode = 1;
    return;
  }
  if (!fs.existsSync(p.patchFile)) {
    out.error = `配置文件不存在: ${p.patchFile}`;
    if (!opts.json) console.error(out.error);
    else process.stdout.write(JSON.stringify(out, null, 2) + '\n');
    process.exitCode = 1;
    return;
  }

  const original = fs.readFileSync(p.patchFile, 'utf8');
  const existingEnv = opts.resetEnv ? {} : parseExistingEnv(original);
  out.preservedEnv = Object.keys(existingEnv);
  const block = buildBlock(p, node.bin, existingEnv);
  // bundle 方式：配置由插件包内的 cordis.patch.yml 提供，这里只清理旧的标记块
  // （从手工安装迁移到插件页安装时会把重复的 mcp 行顺手去掉）。
  const next = byBundle ? patchText(original, block, true) : patchText(original, block, opts.uninstall);
  const changed = next !== original;
  const skillContent = fs.existsSync(p.skillSrc) ? fs.readFileSync(p.skillSrc, 'utf8') : null;
  const skillSame = fs.existsSync(p.skillDest) && fs.readFileSync(p.skillDest, 'utf8') === skillContent;
  const skillWillChange = !opts.uninstall && Boolean(skillContent) && !skillSame;
  const skillWillRemove = opts.uninstall && fs.existsSync(p.skillDest) && skillSame;

  if (opts.dryRun) {
    out.ok = true;
    out.wouldChangePatch = changed;
    out.wouldInstallSkill = skillWillChange;
    out.wouldRemoveSkill = skillWillRemove;
    out.blockPreview = opts.uninstall ? '(将移除标记块)' : block;
    if (opts.json) process.stdout.write(JSON.stringify(out, null, 2) + '\n');
    else {
      console.log('【预览】以下改动尚未写入：');
      console.log(`  profile 配置 : ${p.patchFile}`);
      console.log(`  安装方式     : ${byBundle ? 'bundle（插件包内 cordis.patch.yml 挂载）' : 'patch（写入 cordis.patch.yml 标记块）'}`);
      console.log(`  配置变更     : ${changed ? '有' : '无（已是最新）'}`);
      console.log(`  保留 env     : ${Object.keys(existingEnv).length} 项已有配置${opts.resetEnv ? '（--reset-env：将重置为默认）' : ''}`);
      console.log(`  Skill 安装   : ${skillWillChange ? p.skillDest : '无需变更'}`);
      console.log(`  自动打包     : 安装后生成插件包 + 技能包`);
      console.log(`  Node         : ${node.bin}`);
      console.log('\n将写入的配置块：\n' + (opts.uninstall ? '(卸载：移除标记块)' : byBundle ? '(bundle 模式：不写 profile 配置；若存在旧标记块会被清理)' : block));
    }
    return;
  }

  if (changed) {
    out.backups.push(backup(p.patchFile));
    fs.writeFileSync(p.patchFile, next, 'utf8');
    if (opts.uninstall) out.changes.push(`已移除 ${ID} 配置块`);
    else if (byBundle) out.changes.push(`已清理旧的 ${ID} 配置块（配置改由插件包内的 bundle 提供）`);
    else out.changes.push(`已写入 ${ID} 配置块`);
  }
  if (!opts.uninstall) {
    const sp = writeServerPathFile(p.indexDir, p.serverFile);
    out.serverPath = sp.target;
    if (sp.changed) out.changes.push(`已记录 MCP 入口路径: ${sp.target}`);
  }
  if (skillWillChange) {
    if (fs.existsSync(p.skillDest)) out.backups.push(backup(p.skillDest));
    fs.mkdirSync(path.dirname(p.skillDest), { recursive: true });
    fs.writeFileSync(p.skillDest, skillContent, 'utf8');
    out.changes.push(`已安装 Skill: ${p.skillDest}`);
  }
  if (skillWillRemove) {
    out.backups.push(backup(p.skillDest));
    fs.unlinkSync(p.skillDest);
    out.changes.push(`已移除自动安装的 Skill: ${p.skillDest}`);
  }

  // 安装后自动产出可分发包，无需手工压缩或手动选择文件
  if (!opts.uninstall) {
    try {
      out.packages = packAll().map((r) => ({ mode: r.mode, path: r.path, bytes: r.bytes, fileCount: r.fileCount }));
      out.changes.push('已自动生成插件包与技能包');
    } catch (err) {
      out.changes.push(`自动打包失败（不影响使用）: ${err.message}`);
    }
  }

  out.ok = true;
  out.verify = verify(p, node.bin);
  if (opts.json) process.stdout.write(JSON.stringify(out, null, 2) + '\n');
  else if (opts.uninstall) {
    console.log('卸载完成。');
    for (const c of out.changes) console.log('  - ' + c);
    for (const b of out.backups) console.log('  备份: ' + b);
    console.log('\n完全退出 DSH 桌面端再打开即生效。索引目录可保留，不影响原始会话。');
  } else {
    console.log('安装完成，之后无需再运行任何命令：');
    if (byBundle) {
      console.log('  · 安装方式：DSH bundle（已由插件包内的 cordis.patch.yml 挂载，不写 profile 配置）');
    } else {
      console.log('  · 安装方式：patch（已在 profile 的 cordis.patch.yml 写入受限标记块）');
    }
    for (const c of out.changes.length ? out.changes : ['配置已是最新，无需改动']) console.log('  - ' + c);
    for (const b of out.backups) console.log('  备份: ' + b);
    if (out.preservedEnv.length && !byBundle) console.log(`  已保留原有 env 自定义: ${out.preservedEnv.join(', ')}`);
    if (out.packages?.length) {
      console.log('\n已自动打包（不含任何会话数据/密钥，可直接分发）：');
      for (const pkg of out.packages) {
        console.log(`  · ${pkg.mode}: ${pkg.path} (${pkg.fileCount} 文件 / ${(pkg.bytes / 1024).toFixed(1)} KB)`);
      }
    }
    console.log('\n自动化已开启：');
    console.log('  · server 启动自动建索引（后台子进程，不阻塞 MCP 握手）');
    console.log('  · fs.watch 监听会话目录，新会话写入停止后约数秒自动纳入，无需重启 DSH');
    console.log('  · 每 60 秒定时增量刷新兜底；索引更新会通知 MCP 客户端自动刷新');
    console.log('  · 可用 session_index_status 查看监听状态，session_index_package 随时重打包');
    console.log('\n若工具列表未刷新，完全退出 DSH 桌面端再打开（最小化无效）。');
    console.log('校验：node install.mjs --verify    回滚：node install.mjs --uninstall');
  }
}

try {
  main();
} catch (err) {
  console.error('安装脚本失败：' + err.message);
  process.exitCode = 1;
}
